std::filesystem::path ProjectInfo::GetScriptsRoot() const
{
    if (project_path.empty())
    {
        return {};
    }
    // Peer of <project>/Assets/. See ProjectInfo.h for why this isn't nested
    // under GetProjectContent().
    const char* sd = scripts_dir.empty() ? "Scripts" : scripts_dir.c_str();
    return project_path / sd;
}

