bool ProjectInfo::EnsureScriptsScaffold()
{
    if (project_path.empty())
    {
        // No project loaded - nothing to scaffold. Caller is expected to gate
        // on this; we treat it as a soft no-op to keep Initialize() linear.
        return false;
    }

    bool all_ok = true;
    std::error_code ec;

    // 1) Create directories. create_directories is a no-op if they already exist.
    //    Failures here are logged but non-fatal: the user can still author scripts
    //    by hand, and Phase 2/3 will surface the actual error when they try to use
    //    a missing folder.
    const std::filesystem::path scripts_root = GetScriptsRoot();
    const std::filesystem::path interm_root = GetIntermediateScriptsRoot();
    if (!scripts_root.empty())
    {
        std::filesystem::create_directories(scripts_root, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create scripts dir {}: {}",
                        scripts_root.generic_string(),
                        ec.message());
            all_ok = false;
            ec.clear();
        }
    }
    if (!interm_root.empty())
    {
        std::filesystem::create_directories(interm_root, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create intermediate dir {}: {}",
                        interm_root.generic_string(),
                        ec.message());
            all_ok = false;
            ec.clear();
        }
    }

    // Cooked/ holds per-platform cooked .zasset variants (texture cook Phase 6).
    // Gitignored (it lives under Intermediate/). Created here so the cook step
    // never has to special-case a missing root; the per-platform subdir is made
    // on demand by the cook walk.
    const std::filesystem::path cooked_root = GetIntermediateCookedRoot();
    if (!cooked_root.empty())
    {
        std::filesystem::create_directories(cooked_root, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create cooked dir {}: {}",
                        cooked_root.generic_string(),
                        ec.message());
            ec.clear();
        }
    }

    // AssetRegistry/ holds the path<->GUID maps for text-source assets and
    // IS checked into VCS (see AGENTS.md 2.2). Creating it on first launch
    // means ScriptRegistry can write its JSON without an extra mkdir step.
    const std::filesystem::path registry_root = GetAssetRegistryRoot();
    if (!registry_root.empty())
    {
        std::filesystem::create_directories(registry_root, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create asset-registry dir {}: {}",
                        registry_root.generic_string(),
                        ec.message());
            all_ok = false;
            ec.clear();
        }
    }

    // 2) Write tsconfig.json / package.json only if missing - never overwrite a
    //    user-customised file. This is the same contract as Unity's Library/
    //    autogenerated files (regenerated only when absent).
    const std::filesystem::path packages_root = GetPackagesRoot();
    if (!packages_root.empty())
    {
        std::filesystem::create_directories(packages_root, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create Packages dir {}: {}",
                        packages_root.generic_string(),
                        ec.message());
            all_ok = false;
            ec.clear();
        }
    }
    all_ok &= writeFileIfMissing(GetTsConfigPath(), kTsConfigTemplate);
    all_ok &= writeFileIfMissing(GetPackageJsonPath(), kPackageJsonTemplate);
    all_ok &= writeFileIfMissing(GetProjectPackagesManifestPath(), kProjectPackagesManifestTemplate);

    // 2b) Write the engine-owned typings file. Unlike tsconfig/package.json
    //     this lives under Intermediate/ (gitignored) and is regenerated
    //     unconditionally so it stays in sync with whatever shim ScriptEnv
    //     installs at runtime. Users who want richer typings should add their
    //     own .d.ts under Intermediate/Typings/ -- tsconfig already globs the
    //     whole folder.
    if (!interm_root.empty())
    {
        const std::filesystem::path typings_dir = project_path / (intermediate_dir.empty() ? "Intermediate" : intermediate_dir.c_str()) / "Typings";
        std::filesystem::create_directories(typings_dir, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create typings dir {}: {}",
                        typings_dir.generic_string(),
                        ec.message());
            ec.clear();
        }
        else
        {
            const auto dts_path = typings_dir / "zengine.d.ts";
            std::ofstream ofs(dts_path, std::ios::binary | std::ios::trunc);
            if (!ofs.is_open() || !(ofs << kZEngineDtsTemplate).good())
            {
                LOG_WARNING(ZProjectInfo,
                            "ensureScriptsScaffold: failed to write {}",
                            dts_path.generic_string());
                all_ok = false;
            }
        }
    }

    // 3) Append (not overwrite) ignore rules so users who already have a
    //    .gitignore tracking other patterns keep their existing rules.
    all_ok &= ensureGitignoreSection(project_path / ".gitignore");

    // 4) Shader scaffold. Mirrors steps (1) for the Shaders subsystem:
    //    - <project>/<shaders_dir>/        : user-authored .shader sources
    //    - <project>/<intermediate>/Shaders/: compiled cache (gitignored
    //      automatically because the marker block in step (3) covers the
    //      whole /Intermediate/ tree).
    //    No registry / config files for shaders yet; ShaderRegistry is
    //    deferred until shaders need GUID-stable references (see AGENTS.md
    //    2.2 rationale for ScriptRegistry).
    const std::filesystem::path shaders_root = GetShadersRoot();
    if (!shaders_root.empty())
    {
        std::filesystem::create_directories(shaders_root, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create shaders dir {}: {}",
                        shaders_root.generic_string(),
                        ec.message());
            all_ok = false;
            ec.clear();
        }
    }
    const std::filesystem::path interm_shaders = GetIntermediateShadersRoot();
    if (!interm_shaders.empty())
    {
        std::filesystem::create_directories(interm_shaders, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create intermediate shaders dir {}: {}",
                        interm_shaders.generic_string(),
                        ec.message());
            all_ok = false;
            ec.clear();
        }
    }

    // 5) Data scaffold. Mirrors steps (1)/(4) for the data-table subsystem:
    //    - <project>/<data_dir>/             : user-authored .csv (V1) / .xlsx (V2) sources.
    //    - <content>/_Generated/Data/        : compile output, one .zasset per .csv,
    //      same relative path. Placed UNDER Assets/ so AssetRegistry's existing
    //      scan picks the products up with zero extra wiring; the whole
    //      _Generated/ subtree is gitignored via the marker block in step (3).
    //    No registry yet -- the .zasset header carries its own GUID via
    //    SerializedFile, identical to all other binary assets.
    const std::filesystem::path data_root = GetDataRoot();
    if (!data_root.empty())
    {
        std::filesystem::create_directories(data_root, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create data dir {}: {}",
                        data_root.generic_string(),
                        ec.message());
            all_ok = false;
            ec.clear();
        }
    }
    const std::filesystem::path generated_data = GetGeneratedDataRoot();
    if (!generated_data.empty())
    {
        std::filesystem::create_directories(generated_data, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create generated data dir {}: {}",
                        generated_data.generic_string(),
                        ec.message());
            all_ok = false;
            ec.clear();
        }
    }

    // 5b) Generated Shaders bucket: <content>/_Generated/Shaders/.
    //     Same pattern as _Generated/Data/: placed UNDER Assets/ so
    //     AssetRegistry picks up the .zasset files with zero extra wiring.
    const std::filesystem::path generated_shaders = GetGeneratedShadersRoot();
    if (!generated_shaders.empty())
    {
        std::filesystem::create_directories(generated_shaders, ec);
        if (ec)
        {
            LOG_WARNING(ZProjectInfo,
                        "ensureScriptsScaffold: failed to create generated shaders dir {}: {}",
                        generated_shaders.generic_string(),
                        ec.message());
            all_ok = false;
            ec.clear();
        }
    }

    LOG_INFO(ZProjectInfo,
             "Scripting scaffold ready at {} (scripts: {}, intermediate: {})",
             project_path.generic_string(),
             scripts_root.generic_string(),
             interm_root.generic_string());
    LOG_INFO(ZProjectInfo,
             "Shader scaffold ready (shaders: {}, intermediate: {})",
             shaders_root.generic_string(),
             interm_shaders.generic_string());
    LOG_INFO(ZProjectInfo,
             "Data scaffold ready (data: {}, generated: {})",
             data_root.generic_string(),
             generated_data.generic_string());
    return all_ok;
}

template<typename TransferFunction>
void ProjectInfo::Transfer(TransferFunction& transfer)
{
    transfer.Transfer(name, "name");
    // New scripting fields. Persisted so users can rename Scripts/ → Code/ etc.
    // and have it survive a reload. Defaulted in the header, so existing
    // .zproject files without these keys still load correctly.
    transfer.Transfer(scripts_dir, "scripts_dir");
    transfer.Transfer(intermediate_dir, "intermediate_dir");
    transfer.Transfer(shaders_dir, "shaders_dir");
    transfer.Transfer(data_dir, "data_dir");
}