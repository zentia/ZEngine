#pragma once

// =============================================================================
// PlayerSettings -- the per-project identity of a packaged player.
//
// This used to be a 7-line stub that copied `ProjectInfo::name` into
// `m_ProjectName` and left everything else empty, which had one real
// consequence: `UserPreferences` derives its per-user directory from
// `m_ProductName`, so EVERY project collapsed onto the same "ZEngine"
// preferences folder and shared one preferences.json.
//
// What lives here, and why it is not somewhere else:
//   * `ProjectInfo` is the PROJECT (its directories, its startup level) and is
//     not the place for "what the shipped executable is called".
//   * `UserPreferences` is per-USER and per-machine -- it is where Window.Width
//     ends up once someone drags the corner of the window, not where the
//     project's DEFAULT resolution belongs.
//   * This is therefore project-level, checked-in, and it ships:
//     `<project>/<config_dir>/player_settings.json`, which
//     `ZENGINE_PACKAGE_PROJECT` copies into the package.
//
// Values are JSON (rapidjson), matching the other project-level settings files
// (saved/config/editor_project_prefs.json). It deliberately does NOT go through
// ZCLASS/ZPROPERTY: PlayerSettings is not an Object, and a Transfer-based
// format would have to be regenerated by ZHeaderTool for a plain settings bag.
// =============================================================================

#include "Runtime/Core/Base/EngineSystem.h"
#include "Runtime/Project/ProjectInfo.h"

#include <filesystem>
#include <string>

class PlayerSettings : public IEngineSystem
{
public:
    std::string GetName() const override { return AUTO_GET_CLASS_NAME(); }
    SystemInitPhase GetInitPhase() const override { return SystemInitPhase::PreInit; }
    std::vector<std::type_index> GetDependencies() const override { return {GET_SYSTEM_TYPE(ProjectInfo)}; }
    bool Initialize() override;
    void Shutdown() override {}

    /// The shipped product's name: window title for a standalone build and the
    /// per-user preferences folder. Defaults to the project name, so a project
    /// that never touches this file still gets its own preferences directory
    /// instead of sharing "ZEngine".
    std::string m_ProductName;
    /// Vendor. There is no source for it in ProjectInfo, so it stays a default
    /// until someone sets it.
    std::string m_CompanyName;
    /// Product version. Defaults to the project's version.
    std::string m_Version;
    /// `ProjectInfo::name`. Not persisted -- it IS the project name, and letting
    /// it be overridden would just let the two drift apart.
    std::string m_ProjectName;

    /// Resolution to open with when the user has never resized the window.
    /// `UserPreferences`' Window.Width / Window.Height win once they exist:
    /// those are per-user state, this is the project default.
    int m_DefaultScreenWidth {1280};
    int m_DefaultScreenHeight {720};

    /// `<project>/<config_dir>/player_settings.json`. Empty when no project is
    /// open, in which case `Load()`/`Save()` do nothing and the defaults above
    /// stand -- a player launched without a project is a normal state.
    std::filesystem::path GetSettingsFilePath() const;

    /// Fill the fields from the project's identity. Called by `Initialize()`
    /// before the file is read, so the file only ever overrides, never blanks.
    ///
    /// Takes the two values rather than a `ProjectInfo` so this stays testable
    /// without a registered project -- the mapping from ProjectInfo is
    /// `Initialize()`'s job, and this is the part worth asserting on.
    void ApplyProjectDefaults(const std::string& project_name, const std::string& project_version);

    /// Read `path`. Any key that is absent keeps its current value, so a file
    /// written by an older engine version still loads. Returns false when the
    /// file does not exist or does not parse -- the caller must treat that as
    /// "use the defaults", not as an error.
    bool LoadFromFile(const std::filesystem::path& path);

    /// `LoadFromFile(GetSettingsFilePath())`. False when there is no project.
    bool Load();

    /// Write to `path`, atomically (temp file + rename). False on any I/O
    /// failure: a packaged player can legitimately sit on a read-only install,
    /// and that must not fail startup.
    bool Save(const std::filesystem::path& path) const;

    /// `Save(GetSettingsFilePath())`.
    bool Save() const;
};
