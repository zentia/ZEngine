"""Code emitters: <Name>.generated.h and <Name>.gen.cpp.

The emitted code is intentionally the exact macro sequence a human used to
write by hand (REGISTER_CLASS / DECLARE_OBJECT_SERIALIZE in the class body,
IMPLEMENT_REGISTER_CLASS / IMPLEMENT_OBJECT_SERIALIZE /
INSTANTIATE_TEMPLATE_TRANSFER_EXPORTED + Transfer() in a .cpp), so a migrated
class is byte-for-byte identical to its hand-written form at the
serialization level. Later phases add property metadata and script bindings
on top of the same files.
"""

from __future__ import annotations

from typing import List

from .model import ClassInfo, HeaderInfo

TOOL_VERSION = 1

_BANNER = (
    "// ==========================================================================\n"
    "// Generated by ZHeaderTool v{version} -- DO NOT EDIT. Changes will be lost.\n"
    "// Source: {source}\n"
    "// ==========================================================================\n"
)


def _banner(header: HeaderInfo) -> str:
    return _BANNER.format(version=TOOL_VERSION, source=header.include_path)


def _macro(name: str, lines: List[str]) -> str:
    body = " \\\n".join("    " + line if line and not line.endswith(":") else line for line in lines)
    return "#define %s \\\n%s\n" % (name, body)


def generated_body_macro_name(cls: ClassInfo) -> str:
    return "ZGEN_BODY_" + cls.name


def generate_header(header: HeaderInfo) -> str:
    out = [_banner(header), "#pragma once\n", "\n", '#include "Runtime/BaseClasses/ObjectMacros.h"\n']
    for cls in header.classes:
        lines: List[str] = []
        if cls.abstract:
            lines.append("REGISTER_CLASS_TRAITS(kTypeIsAbstract);")
        lines.append("REGISTER_CLASS(%s);" % cls.name)
        lines.append("DECLARE_OBJECT_SERIALIZE();")
        # Restore the default access of the class-key so code written right
        # after ZGENERATED_BODY() behaves as if the macro were not there.
        lines.append("private:" if cls.class_key == "class" else "public:")
        out.append("\n")
        out.append("// ---- %s (%s:%d) ----\n" % (cls.name, header.include_path, cls.line))
        out.append(_macro(generated_body_macro_name(cls), lines))
    return "".join(out)


def _transfer_call(prop) -> str:
    if prop.transfer_flags:
        flags = " | ".join("TransferMetaFlags::" + f for f in prop.transfer_flags)
        return 'transfer.Transfer(%s, "%s", %s);' % (prop.member_name, prop.serialized_name, flags)
    return 'transfer.Transfer(%s, "%s");' % (prop.member_name, prop.serialized_name)


def generate_source(header: HeaderInfo) -> str:
    out = [_banner(header), "\n", '#include "%s"\n' % header.include_path]
    for cls in header.classes:
        out.append("\n")
        out.append("// ---- %s ----\n" % cls.name)
        out.append("IMPLEMENT_REGISTER_CLASS(%s)\n" % cls.name)
        if cls.custom_transfer:
            out.append("// ZCLASS(CustomTransfer): IMPLEMENT_OBJECT_SERIALIZE, Transfer() and\n")
            out.append("// INSTANTIATE_TEMPLATE_TRANSFER_EXPORTED live in the hand-written .cpp.\n")
            continue
        out.append("IMPLEMENT_OBJECT_SERIALIZE(%s)\n" % cls.name)
        out.append("\n")
        out.append("template<typename TransferFunction>\n")
        out.append("void %s::Transfer(TransferFunction& transfer)\n" % cls.name)
        out.append("{\n")
        out.append("    Super::Transfer(transfer);\n")
        for prop in cls.properties:
            if prop.transient:
                continue
            out.append("    %s\n" % _transfer_call(prop))
        out.append("}\n")
        out.append("\n")
        out.append("INSTANTIATE_TEMPLATE_TRANSFER_EXPORTED(%s)\n" % cls.name)
    return "".join(out)
