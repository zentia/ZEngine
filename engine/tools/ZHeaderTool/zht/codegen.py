"""Code emitters: <Name>.generated.h and <Name>.gen.cpp.

The emitted code is intentionally the exact macro sequence a human used to
write by hand (REGISTER_CLASS / DECLARE_OBJECT_SERIALIZE in the class body,
IMPLEMENT_REGISTER_CLASS / IMPLEMENT_OBJECT_SERIALIZE /
INSTANTIATE_TEMPLATE_TRANSFER_EXPORTED + Transfer() in a .cpp), so a migrated
class is byte-for-byte identical to its hand-written form at the
serialization level. Later phases add property metadata and script bindings
on top of the same files.
"""

from __future__ import annotations

from typing import Dict, List, Optional, Tuple

from .model import ClassInfo, HeaderInfo
from .parser import script_property_name, script_property_ts_type

TOOL_VERSION = 7

_BANNER = (
    "// ==========================================================================\n"
    "// Generated by ZHeaderTool v{version} -- DO NOT EDIT. Changes will be lost.\n"
    "// Source: {source}\n"
    "// ==========================================================================\n"
)


def _banner(header: HeaderInfo) -> str:
    return _BANNER.format(version=TOOL_VERSION, source=header.include_path)


def _macro(name: str, lines: List[str]) -> str:
    body = " \\\n".join("    " + line if line and not line.endswith(":") else line for line in lines)
    return "#define %s \\\n%s\n" % (name, body)


def generated_body_macro_name(cls: ClassInfo) -> str:
    return "ZGEN_BODY_" + cls.name


def _enum_block(header: HeaderInfo) -> List[str]:
    """Runtime (name, value) table for every ZENUM in this header (phase 8).

    The table is the single source for both halves of an enum: the d.ts
    `declare enum` (generated from the same entries) and the JS object
    `InstallGlobals` publishes so `CameraMode.Free` resolves at runtime. A
    `declare enum` with no runtime object would type-check and then evaluate to
    undefined.
    """
    if not header.enums:
        return []
    out: List[str] = []
    for enum in header.enums:
        ident = enum.qualified_name.replace("::", "_")
        out.append("\nnamespace\n{\n")
        out.append("    const ZScriptEnumEntry kZhtScriptEnumValues_%s[] = {\n" % ident)
        out.extend('        {.name = "%s", .value = %d},\n' % (v.ts_name, v.value) for v in enum.values)
        out.append("    };\n")
        out.append('    ZScriptEnum kZhtScriptEnum_%s {"%s", kZhtScriptEnumValues_%s, %d};\n'
                   % (ident, enum.name, ident, len(enum.values)))
        out.append("    const ZScriptEnumRegistrar kZhtScriptEnumRegistrar_%s(kZhtScriptEnum_%s);\n" % (ident, ident))
        out.append("}  // namespace\n")
    return out


def _field_ts_type(cpp_type: str, script_enums: Dict[str, str]) -> Optional[str]:
    """TypeScript type of a ZPROPERTY field, or None when it is not marshallable.

    `script_enums` maps the C++ spelling a field is written with (both the
    qualified and, when unambiguous, the bare name) to the enum's script name,
    so a ZENUM-annotated field is declared as `mode: CameraMode` and not as
    `mode: number`.
    """
    text = " ".join(cpp_type.split())
    known = script_property_ts_type(text)
    if known is not None:
        return known
    return script_enums.get(text)


def _script_field_properties(cls: ClassInfo, script_enums: Optional[Dict[str, str]] = None) -> List[Tuple[object, str]]:
    """(ZPROPERTY field, TypeScript type) pairs exposed as script properties.

    A field only qualifies when its type has a ZScript::Converter; see
    parser._SCRIPT_PROPERTY_TYPES and the ZENUM table. Everything else (PPtr, a
    Res struct, std::vector, a non-ZENUM enum) is skipped silently -- ZPROPERTY
    marks a field as *serialized*, not as script-facing, so an unmarshallable
    type must not turn into a generate-time error.

    Scope note: fields only contribute to a class that is already script-visible
    (it owns ZFUNCTIONs or a ZSCRIPTPROPERTY). Widening this to "any class with a
    marshallable field" would publish ~30 more globals and `declare class`es at
    once; that is a separate decision, and this predicate is where to make it.
    """
    if not (cls.methods or cls.script_properties):
        return []
    out: List[Tuple[object, str]] = []
    for prop in cls.properties:
        ts_type = _field_ts_type(prop.cpp_type, script_enums or {})
        if ts_type is not None:
            out.append((prop, ts_type))
    return out


def _is_readonly_field(prop) -> bool:
    # ZPROPERTY(ReadOnly) maps to DisallowSerializedPropertyModification. The
    # Inspector does not honour it yet, but the script property does: writing a
    # field the engine treats as read-only (a script GUID, say) would desync
    # state the runtime has already indexed.
    return "DisallowSerializedPropertyModification" in prop.transfer_flags


def script_accessor_getter_name(member_name: str) -> str:
    return "ZhtScriptGet_" + member_name


def script_accessor_setter_name(member_name: str) -> str:
    return "ZhtScriptSet_" + member_name


def generate_header(header: HeaderInfo, script_enums: Optional[Dict[str, str]] = None) -> str:
    out = [_banner(header), "#pragma once\n", "\n", '#include "Runtime/BaseClasses/ObjectMacros.h"\n']
    for cls in header.classes:
        lines: List[str] = []
        if cls.abstract:
            lines.append("REGISTER_CLASS_TRAITS(kTypeIsAbstract);")
        lines.append("REGISTER_CLASS(%s);" % cls.name)
        lines.append("DECLARE_OBJECT_SERIALIZE();")
        # Accessors for script-exposed fields. They have to be PUBLIC: the
        # .gen.cpp takes their address from file scope, and C++ checks access
        # at the point of naming -- the fields themselves are usually private.
        # Definitions are emitted next to Transfer(), whose member context is
        # what reaches the private field in the first place.
        accessors: List[str] = []
        for prop, _ts in _script_field_properties(cls, script_enums):
            accessors.append("%s %s() const;" % (prop.cpp_type, script_accessor_getter_name(prop.member_name)))
            if not _is_readonly_field(prop):
                accessors.append("void %s(const %s& value);" % (script_accessor_setter_name(prop.member_name), prop.cpp_type))
        if accessors:
            lines.append("public:")
            lines.extend(accessors)
        # Restore the default access of the class-key so code written right
        # after ZGENERATED_BODY() behaves as if the macro were not there.
        lines.append("private:" if cls.class_key == "class" else "public:")
        out.append("\n")
        out.append("// ---- %s (%s:%d) ----\n" % (cls.name, header.include_path, cls.line))
        out.append(_macro(generated_body_macro_name(cls), lines))
    return "".join(out)


def _transfer_call(prop) -> str:
    if prop.transfer_flags:
        flags = " | ".join("TransferMetaFlags::" + f for f in prop.transfer_flags)
        return 'transfer.Transfer(%s, "%s", %s);' % (prop.member_name, prop.serialized_name, flags)
    return 'transfer.Transfer(%s, "%s");' % (prop.member_name, prop.serialized_name)


_TRANSFER_INCLUDES = (
    # Every TransferFunction named by INSTANTIATE_TEMPLATE_TRANSFER_EXPORTED
    # must be a complete type at the instantiation point.
    "Runtime/Core/Serialize/TransferFunctions/SerializeTransfer.h",
    "Runtime/Core/Serialize/TransferFunctions/SafeBinaryRead.h",
    "Runtime/Core/Serialize/TransferFunctions/GenerateTypeTreeTransfer.h",
)


def _register_line(cls: ClassInfo) -> str:
    if cls.namespace:
        return "IMPLEMENT_REGISTER_CLASS_3(%s, %s, typeid(%s).hash_code())\n" % (cls.namespace, cls.name, cls.qualified_name)
    return "IMPLEMENT_REGISTER_CLASS(%s)\n" % cls.name


def _transfer_definition(cls: ClassInfo, indent: str) -> List[str]:
    out = [
        indent + "template<typename TransferFunction>\n",
        indent + "void %s::Transfer(TransferFunction& transfer)\n" % cls.name,
        indent + "{\n",
    ]
    body: List[str] = []
    if not cls.no_super_transfer:
        body.append("Super::Transfer(transfer);")
    for prop in cls.properties:
        if not prop.transient:
            body.append(_transfer_call(prop))
    if not body:
        body.append("(void)transfer;")
    out.extend(indent + "    " + line + "\n" for line in body)
    out.append(indent + "}\n")
    out.append("\n")
    out.append(indent + "INSTANTIATE_TEMPLATE_TRANSFER_EXPORTED(%s)\n" % cls.name)
    return out


def _cpp_number(value) -> str:
    text = repr(float(value))
    return text if any(ch in text for ch in ".eE") or text in ("inf", "-inf", "nan") else text + ".0"


def _property_meta_entry(prop) -> str:
    """One ZPropertyMeta aggregate. Designated initializers, in declaration
    order of ZPropertyMeta (Runtime/BaseClasses/PropertyMeta.h)."""
    fields = ['.serializedName = "%s"' % prop.serialized_name]
    for key, member in (("DisplayName", "displayName"), ("Tooltip", "tooltip"), ("Category", "category")):
        if key in prop.meta:
            # String tokens keep their escapes verbatim, so re-quoting is safe.
            fields.append('.%s = "%s"' % (member, prop.meta[key]))
    if prop.edit_condition:
        fields.append('.editCondition = "%s"' % prop.edit_condition)
    for key, has_member, member in (("ClampMin", "hasClampMin", "clampMin"), ("ClampMax", "hasClampMax", "clampMax"),
                                    ("UIMin", "hasUIMin", "uiMin"), ("UIMax", "hasUIMax", "uiMax")):
        if key in prop.meta:
            fields.append(".%s = true" % has_member)
            fields.append(".%s = %s" % (member, _cpp_number(prop.meta[key])))
    return "{" + ", ".join(fields) + "}"


def _meta_block(cls: ClassInfo) -> List[str]:
    props = [p for p in cls.properties if p.meta and not p.transient]
    if not props:
        return []
    ident = cls.qualified_name.replace("::", "_")
    out = ["\n", "namespace\n{\n"]
    out.append("    const ZPropertyMeta kZhtPropertyMeta_%s[] = {\n" % ident)
    out.extend("        %s,\n" % _property_meta_entry(p) for p in props)
    out.append("    };\n")
    out.append("    ZClassPropertyMeta kZhtClassMeta_%s {TypeOf<%s>(), kZhtPropertyMeta_%s, %d};\n" % (ident, cls.qualified_name, ident, len(props)))
    out.append("    const ZPropertyMetaRegistrar kZhtMetaRegistrar_%s(kZhtClassMeta_%s);\n" % (ident, ident))
    out.append("}  // namespace\n")
    return out


def _function_pointer_type(cls: ClassInfo, method) -> str:
    """The exact C++ function-pointer type of `method`, used to disambiguate
    overloads when taking its address."""
    params = ", ".join(p.cpp_type for p in method.params)
    qualifier = " const" if method.is_const else ""
    if method.is_static:
        return "%s (*)(%s)" % (method.return_type, params)
    return "%s (%s::*)(%s)%s" % (method.return_type, cls.qualified_name, params, qualifier)


def _script_method_entry(cls: ClassInfo, method) -> str:
    target = "&%s::%s" % (cls.qualified_name, method.name)
    pointer = "static_cast<%s>(%s)" % (_function_pointer_type(cls, method), target)
    callback = "&ZScript::MethodCallback<%s>::Invoke" % pointer
    return ('{.name = "%s", .tsSignature = "%s", .isStatic = %s, .callback = %s}'
            % (method.ts_name, method.ts_signature.replace('"', '\\"'), "true" if method.is_static else "false", callback))


def _signature_type_names(cls: ClassInfo) -> List[str]:
    """Every named type a bound signature mentions (return + parameters).

    Used to pull in the headers that make those types COMPLETE: the
    ZScript::Converter<T*> specialisation static_asserts on
    std::is_base_of<Object, T>, which is a hard error on a type that is only
    forward-declared -- and reflected headers routinely forward-declare each
    other (Component.h / GameObject.h / Transform.h form such a cycle).
    """
    names: List[str] = []
    for method in cls.methods:
        raw = [method.return_type] + [p.cpp_type for p in method.params]
        for text in raw:
            for token in text.replace("*", " ").replace("&", " ").split():
                if token in ("const", "volatile", "struct", "class", "typename"):
                    continue
                if token and token not in names:
                    names.append(token)
    return names


def _script_signature_includes(header: HeaderInfo, type_headers: Dict[str, str]) -> List[str]:
    if not type_headers:
        return []
    needed: List[str] = []
    seen = {header.include_path}
    for cls in header.classes:
        for name in _signature_type_names(cls):
            inc = type_headers.get(name)
            if inc and inc not in seen:
                seen.add(inc)
                needed.append(inc)
    return sorted(needed)


def _effective_super(cls: ClassInfo, bound: set, bases: Dict[str, Optional[str]]) -> Optional[str]:
    """The nearest ancestor that actually owns a script binding.

    An intermediate base with no ZFUNCTION of its own (Behaviour, say) cannot
    be a link in the pesapi prototype chain: `InstallAll` would have to
    declare it as a root placeholder, which silently drops every method the
    real ancestors above it contributed. Walking up to the nearest bound
    ancestor keeps the chain intact and flattens the empty middle -- the same
    thing UE's UHT does for non-reflected mixin layers.
    """
    base = cls.base
    while base is not None and base not in bound:
        nxt = bases.get(base)
        if nxt is None:
            # Not a reflected class of this module -- keep it so InstallAll
            # still emits the placeholder declaration (e.g. Object).
            return base
        base = nxt
    return base


def _script_accessor_definitions(cls: ClassInfo, indent: str, script_enums: Optional[Dict[str, str]] = None) -> List[str]:
    """Definitions of the generated field accessors (member context, so they
    can touch private fields)."""
    out: List[str] = []
    for prop, _ts in _script_field_properties(cls, script_enums):
        q = cls.qualified_name
        out.append("%s%s %s::%s() const { return %s; }\n"
                   % (indent, prop.cpp_type, q, script_accessor_getter_name(prop.member_name), prop.member_name))
        if not _is_readonly_field(prop):
            out.append("%svoid %s::%s(const %s& value) { %s = value; }\n"
                       % (indent, q, script_accessor_setter_name(prop.member_name), prop.cpp_type, prop.member_name))
    return out


def _script_accessor_block(cls: ClassInfo, script_enums: Optional[Dict[str, str]] = None) -> List[str]:
    defs = _script_accessor_definitions(cls, "    " if cls.namespace else "", script_enums)
    if not defs:
        return []
    out: List[str] = ["\n"]
    if cls.namespace:
        out.append("namespace %s\n{\n" % cls.namespace)
        out.extend(defs)
        out.append("}  // namespace %s\n" % cls.namespace)
    else:
        out.extend(defs)
    return out


def _script_property_entries(cls: ClassInfo, script_enums: Optional[Dict[str, str]] = None) -> List[str]:
    """pesapi accessor property table: ZPROPERTY fields first, then the
    ZSCRIPTPROPERTY accessor pairs.

    Both kinds end up as the same ZScriptPropertyEntry, and in both cases the
    trampoline is the ordinary ZScript::MethodCallback -- a property getter is
    just a zero-argument method that returns a value, and a setter is a
    one-argument method. No new marshalling machinery is needed.
    """
    out: List[str] = []
    q = cls.qualified_name
    for prop, ts in _script_field_properties(cls, script_enums):
        readonly = _is_readonly_field(prop)
        getter = ("&ZScript::MethodCallback<static_cast<%s (%s::*)() const>(&%s::%s)>::Invoke"
                  % (prop.cpp_type, q, q, script_accessor_getter_name(prop.member_name)))
        setter = "nullptr"
        if not readonly:
            setter = ("&ZScript::MethodCallback<static_cast<void (%s::*)(const %s&)>(&%s::%s)>::Invoke"
                      % (q, prop.cpp_type, q, script_accessor_setter_name(prop.member_name)))
        out.append('{.name = "%s", .tsType = "%s", .readonly = %s, .getter = %s, .setter = %s}'
                   % (script_property_name(prop.serialized_name), ts,
                      "true" if readonly else "false", getter, setter))

    by_name = {m.name: m for m in cls.methods}
    for sp in cls.script_properties:
        getter = "&ZScript::MethodCallback<static_cast<%s>(&%s::%s)>::Invoke" % (
            _function_pointer_type(cls, by_name[sp.getter]), q, sp.getter)
        setter = "nullptr"
        if sp.setter:
            setter = "&ZScript::MethodCallback<static_cast<%s>(&%s::%s)>::Invoke" % (
                _function_pointer_type(cls, by_name[sp.setter]), q, sp.setter)
        out.append('{.name = "%s", .tsType = "%s", .readonly = %s, .getter = %s, .setter = %s}'
                   % (sp.name, sp.ts_type, "true" if not sp.setter else "false", getter, setter))
    return out


def _script_block(cls: ClassInfo, super_name: Optional[str], script_enums: Optional[Dict[str, str]] = None) -> List[str]:
    """Static pesapi binding table for one class (methods + properties)."""
    properties = _script_property_entries(cls, script_enums)
    if not cls.methods and not properties:
        return []
    ident = cls.qualified_name.replace("::", "_")
    super_type = "ZScriptTypeId<%s>::Get()" % super_name if super_name else "nullptr"
    super_name_lit = '"%s"' % super_name if super_name else "nullptr"
    out = ["\n", "namespace\n{\n"]
    if cls.methods:
        out.append("    const ZScriptMethodEntry kZhtScriptMethods_%s[] = {\n" % ident)
        out.extend("        %s,\n" % _script_method_entry(cls, m) for m in cls.methods)
        out.append("    };\n")
    if properties:
        out.append("    const ZScriptPropertyEntry kZhtScriptProperties_%s[] = {\n" % ident)
        out.extend("        %s,\n" % entry for entry in properties)
        out.append("    };\n")
    out.append("    ZClassScriptBinding kZhtScriptClass_%s {ZScriptTypeId<%s>::Get(), %s, \"%s\", %s, %s, %d, %s, %d};\n"
               % (ident, cls.qualified_name, super_type, cls.name, super_name_lit,
                  "kZhtScriptMethods_%s" % ident if cls.methods else "nullptr", len(cls.methods),
                  "kZhtScriptProperties_%s" % ident if properties else "nullptr", len(properties)))
    out.append("    const ZClassScriptBindingRegistrar kZhtScriptRegistrar_%s(kZhtScriptClass_%s);\n" % (ident, ident))
    out.append("}  // namespace\n")
    return out


def generate_source(header: HeaderInfo, type_headers: Optional[Dict[str, str]] = None,
                    bound_classes: Optional[set] = None, base_of: Optional[Dict[str, Optional[str]]] = None,
                    script_enums: Optional[Dict[str, str]] = None) -> str:
    enums = script_enums or {}
    out = [_banner(header), "\n", '#include "%s"\n' % header.include_path]
    needs_meta = any(p.meta and not p.transient for cls in header.classes for p in cls.properties)
    needs_script = any(cls.methods or cls.script_properties for cls in header.classes)
    needs_enum = bool(header.enums)
    script_includes = _script_signature_includes(header, type_headers or {}) if needs_script else []
    if any(not cls.custom_transfer for cls in header.classes) or needs_meta or needs_script or needs_enum:
        out.append("\n")
        if needs_meta:
            out.append('#include "Runtime/BaseClasses/PropertyMeta.h"\n')
        if needs_script or needs_enum:
            out.append('#include "Runtime/Scripting/Binding/ScriptBinding.h"\n')
            out.extend('#include "%s"\n' % inc for inc in script_includes)
        if any(not cls.custom_transfer for cls in header.classes):
            out.extend('#include "%s"\n' % inc for inc in _TRANSFER_INCLUDES)
    if needs_enum:
        out.extend(_enum_block(header))
    for cls in header.classes:
        out.append("\n")
        out.append("// ---- %s ----\n" % cls.qualified_name)
        out.append(_register_line(cls))
        super_name = _effective_super(cls, bound_classes or set(), base_of or {})
        if cls.custom_transfer:
            out.append("// ZCLASS(CustomTransfer): IMPLEMENT_OBJECT_SERIALIZE, Transfer() and\n")
            out.append("// INSTANTIATE_TEMPLATE_TRANSFER_EXPORTED live in the hand-written .cpp.\n")
            out.extend(_meta_block(cls))
            out.extend(_script_accessor_block(cls, enums))
            out.extend(_script_block(cls, super_name, enums))
            continue
        out.append("IMPLEMENT_OBJECT_SERIALIZE(%s)\n" % cls.qualified_name)
        out.append("\n")
        if cls.namespace:
            out.append("namespace %s\n{\n" % cls.namespace)
            out.extend(_transfer_definition(cls, "    "))
            out.append("}  // namespace %s\n" % cls.namespace)
        else:
            out.extend(_transfer_definition(cls, ""))
        out.extend(_meta_block(cls))
        out.extend(_script_accessor_block(cls, enums))
        out.extend(_script_block(cls, super_name, enums))
    return "".join(out)
